"""Capture the User's Guide screenshots with Playwright + Google Chrome.

    cd rs3d-app && uv run python ../docs/manual/scripts/make_screenshots.py
Output: docs/manual/figures/ug-*.png (the app runs against the synthetic demo day, see demo_data.py).
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

from obspy import UTCDateTime
from playwright.sync_api import sync_playwright

HERE = Path(__file__).resolve().parent
FIG = HERE.parent / "figures"
BUILD = HERE.parent / "build"
sys.path.insert(0, str(HERE))
import demo_data as dd  # noqa: E402

from rs3d.core.store import Store  # noqa: E402

PORT = 8861
BASE = f"http://127.0.0.1:{PORT}"
DAY_START = dd.DAY.timestamp


def epoch(hhmmss: str) -> int:
    return int(UTCDateTime(f"2026-10-15T{hhmmss}").timestamp)


def prepare(tmp: Path) -> Path:
    BUILD.mkdir(parents=True, exist_ok=True)
    mseed = BUILD / "demo_day.mseed"
    if not mseed.exists():
        dd.make_day().write(str(mseed), format="MSEED")
    root = tmp / "rs3d"
    root.mkdir()
    Store(root / "sds").import_file(mseed)
    return root


def start_server(root: Path) -> subprocess.Popen:
    env = {k: v for k, v in os.environ.items() if k != "PYTEST_CURRENT_TEST"}
    env["RS3D_DATA_DIR"] = str(root)
    env["DEMO_MSEED"] = str(BUILD / "demo_day.mseed")
    proc = subprocess.Popen([sys.executable, str(HERE / "screenshot_app.py"), str(PORT)], env=env,
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for _ in range(150):
        try:
            urllib.request.urlopen(BASE, timeout=1)
            return proc
        except OSError:
            time.sleep(0.3)
    proc.terminate()
    raise RuntimeError("the screenshot app did not start")


def main() -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    base = Path("/tmp/rs3d-manual-demo")        # a fixed, readable path: it is visible on the Settings page
    shutil.rmtree(base, ignore_errors=True)
    base.mkdir(parents=True)
    try:
        root = prepare(base)
        proc = start_server(root)
        try:
            with sync_playwright() as p:
                browser = p.chromium.launch(channel="chrome", headless=True)
                page = browser.new_page(viewport={"width": 1400, "height": 900}, device_scale_factor=1.25,
                                        accept_downloads=True)
                capture(page)
                browser.close()
        finally:
            proc.terminate()
    finally:
        shutil.rmtree(base, ignore_errors=True)
    optimise()
    (FIG / "ug-callouts.tex").write_text("% generated by make_screenshots.py\n" + "".join(CALLOUT_TEX))
    print("  wrote ug-callouts.tex")


def optimise() -> None:
    """256-colour PNGs: about five times smaller with no visible change for screenshots."""
    from PIL import Image
    for path in sorted(FIG.glob("ug-*.png")):
        Image.open(path).convert("RGB").quantize(colors=256, method=Image.Quantize.FASTOCTREE,
                                                 dither=Image.Dither.FLOYDSTEINBERG).save(path, optimize=True)


VIEWPORT = {"x": 0, "y": 0, "width": 1400, "height": 900}
CALLOUT_TEX: list[str] = []


def shot(page, name: str, full: bool = False, locator=None, clip=None) -> None:
    path = str(FIG / f"ug-{name}.png")
    if locator is not None:
        locator.screenshot(path=path)
    elif clip is not None:
        page.screenshot(path=path, clip=clip)
    else:
        page.screenshot(path=path, full_page=full)
    print("  wrote", name)


def callouts(macro: str, clip: dict, items, place: str = "left") -> None:
    """Write \\macro = 'x/y/n, ...' with the measured position of each element, as fractions of `clip`.

    Each item is (number, locator) or (number, locator, (fx, fy)) to aim at a fraction of the element's box.
    place="left" puts the marker just left of the element; place="above" puts it above its centre (toolbars)."""
    parts = []
    for item in items:
        n, loc = item[0], item[1]
        bb = loc.first.bounding_box()
        fx, fy = item[2] if len(item) > 2 else (0.0, 0.0)
        if place == "above":
            px, py = bb["x"] + bb["width"] * (fx or 0.5), bb["y"] - 15
        else:
            px, py = bb["x"] + bb["width"] * fx - 13, bb["y"] + bb["height"] * fy + 7
        parts.append(f"{(px - clip['x']) / clip['width']:.4f}/{1 - (py - clip['y']) / clip['height']:.4f}/{n}")
    CALLOUT_TEX.append(f"\\newcommand{{\\{macro}}}{{{', '.join(parts)}}}\n")


def echarts(page):
    return page.locator(".nicegui-echart")


