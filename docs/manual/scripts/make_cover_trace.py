"""Write common/cover_trace.tex: the decorative seismogram on the cover pages (deterministic)."""
from pathlib import Path

import numpy as np

rng = np.random.default_rng(7)
x = np.linspace(0, 21, 700)                       # cm across the page
noise = rng.normal(0, 1, x.size)
noise = np.convolve(noise, np.ones(3) / 3, mode="same") * 0.035
t0, ts = 8.6, 10.4                                # P and S "arrivals" (cm)
p = np.where(x > t0, np.exp(-(x - t0) * 0.75) * np.sin(34 * (x - t0)) * 0.55, 0)
s = np.where(x > ts, np.exp(-(x - ts) * 0.35) * np.sin(24 * (x - ts)) * 1.25 * np.minimum((x - ts) * 3, 1), 0)
y = noise + p + s
coords = " ".join(f"({a:.3f},{b:.3f})" for a, b in zip(x, y))
out = Path(__file__).resolve().parents[1] / "common" / "cover_trace.tex"
out.write_text("% generated by scripts/make_cover_trace.py\n\\newcommand{\\covertrace}{" + coords + "}\n")
print(out, out.stat().st_size, "bytes")
